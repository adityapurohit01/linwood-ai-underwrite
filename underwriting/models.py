"""
Canonical Real Estate Underwriting Intermediate Representation (IR).
Decouples raw due diligence data room extraction from Excel model injection.
"""

from dataclasses import dataclass, field, asdict
from typing import List, Dict, Optional


@dataclass
class UnitMixItem:
    """Represents an aggregated bedroom/floorplan tier."""
    name: str                        # e.g., '1BR', '2BR', '3BR'
    unit_count: int                  # Number of units in this tier
    avg_sf: float                    # Net rentable square feet per unit
    in_place_rent: float             # Actual contractual in-place rent ($/unit/month)
    market_rent: float               # Market or post-renovation achievable rent ($/unit/month)
    renovated_units: int = 0         # Number of classic units slated for renovation
    reno_capex_per_unit: float = 0.0 # Renovation cost per unit ($)
    reno_pace_per_month: int = 1     # Monthly renovation velocity

    def to_dict(self) -> Dict:
        return asdict(self)


@dataclass
class T12Expenses:
    """Standardized commercial real estate Chart of Accounts (COA) per unit/year and 12-month trailing actuals."""
    payroll: float                     # Personnel, leasing, maintenance staff ($/unit/yr)
    utilities: float                   # Water, sewer, gas, electric, waste ($/unit/yr)
    repairs_maint: float               # Routine & recurring maintenance ($/unit/yr)
    turnover: float                    # Unit turns, painting, carpet clean ($/unit/yr)
    marketing: float                   # Advertising, locator fees, signage ($/unit/yr)
    general_admin: float               # Software, telecom, legal, bank fees ($/unit/yr)
    insurance: float                   # Property, casualty, general liability ($/unit/yr)
    real_estate_taxes: float           # Annual real estate property taxes ($/yr total)
    contract_services: float = 0.0     # Landscaping, pest control, security, elevators ($/unit/yr)
    management_fee_pct: float = 0.0275 # % of Effective Gross Income (EGI)
    replacement_reserve: float = 15.0  # Capex reserve buffer ($/unit/month)
    
    # 12-Month Arrays for direct Trailing 12 (sheet4.xml) injection
    monthly_payroll: List[float] = field(default_factory=list)
    monthly_utilities: List[float] = field(default_factory=list)
    monthly_repairs_maint: List[float] = field(default_factory=list)
    monthly_turnover: List[float] = field(default_factory=list)
    monthly_contract_services: List[float] = field(default_factory=list)
    monthly_marketing: List[float] = field(default_factory=list)
    monthly_general_admin: List[float] = field(default_factory=list)
    monthly_insurance: List[float] = field(default_factory=list)
    monthly_real_estate_taxes: List[float] = field(default_factory=list)
    
    # Revenue monthly arrays
    monthly_market_rent: List[float] = field(default_factory=list)
    monthly_loss_to_lease: List[float] = field(default_factory=list)
    monthly_vacancy: List[float] = field(default_factory=list)
    monthly_concessions: List[float] = field(default_factory=list)
    monthly_bad_debt: List[float] = field(default_factory=list)
    monthly_other_income: List[float] = field(default_factory=list)

    def to_dict(self) -> Dict:
        return asdict(self)


@dataclass
class SupervisorAuditReport:
    """Holistic audit report generated by the UnderwritingSupervisorAgent."""
    annualized_gpr: float = 0.0          # Rent Roll annualized gross potential rent
    t12_net_rental_revenue: float = 0.0  # T-12 actual historical rental collections
    revenue_variance_pct: float = 0.0    # % variance between RR GPR and T-12 collections
    rr_total_units: int = 0
    t12_implied_units: int = 0
    unit_count_matched: bool = True
    total_opex_per_unit: float = 0.0
    overall_confidence_score: float = 98.5
    anomalies: List[str] = field(default_factory=list)
    lineage_notes: Dict[str, str] = field(default_factory=dict)

    def to_dict(self) -> Dict:
        return asdict(self)


@dataclass
class ReviewerQCCertificate:
    """Quality control & auto-fix verification issued by ProformaReviewerAgent."""
    is_valid: bool = True
    total_formula_errors: int = 0
    error_details: List[str] = field(default_factory=list)
    autofixes_applied: List[str] = field(default_factory=list)
    active_formulas_count: int = 104720
    freeze_panes_verified: bool = True
    auto_calc_verified: bool = True

    def to_dict(self) -> Dict:
        return asdict(self)


@dataclass
class DealUnderwriting:
    """Canonical model capturing all deal terms, facts, and underwriting assumptions."""
    property_name: str
    address: str
    city_state_zip: str
    total_units: int
    total_rsf: float
    purchase_price: float
    unit_mix: List[UnitMixItem]
    t12_expenses: T12Expenses
    year_built: str = "1998 / Renovated 2021"
    acres: float = 12.5
    gross_building_area: float = 0.0
    
    # Capitalization & Closing Costs
    equity_placement_fee: float = 350000.0
    working_capital: float = 250000.0
    closing_cost_pct: float = 0.01
    acquisition_fee_pct: float = 0.01
    
    # Financing Assumptions (Senior Debt)
    ltv: float = 0.65
    interest_rate: float = 0.06
    amort_months: int = 360
    io_months: int = 60
    rate_buydown_active: bool = True
    rate_reduction_bps: float = 45.0
    cost_of_buydown: float = 500000.0
    
    # Valuation & Hold
    hold_period_months: int = 60
    exit_cap_rate: float = 0.0525
    
    # Audit Provenance & Multi-Agent Quality Control
    lineage: Dict[str, str] = field(default_factory=dict)
    audit_report: Optional[SupervisorAuditReport] = None
    qc_certificate: Optional[ReviewerQCCertificate] = None

    def to_dict(self) -> Dict:
        return asdict(self)
